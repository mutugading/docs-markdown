PROMPT == 5. Fungsi generate NIK ==
-- Tidak autonomous: counter ikut transaksi INSERT (rollback insert = rollback nomor).
-- Row lock pada baris (company, periode) -> serialisasi per company per bulan join.
CREATE OR REPLACE FUNCTION MGTHRIS.FN_GEN_NIK (p_comp_id IN VARCHAR2, p_join_date IN DATE) RETURN VARCHAR2
IS
  v_period VARCHAR2(6);
  v_no     NUMBER;
BEGIN
  IF p_comp_id IS NULL THEN
    RAISE_APPLICATION_ERROR(-20904, 'Company wajib diisi untuk membuat NIK');
  END IF;
  IF p_join_date IS NULL THEN
    RAISE_APPLICATION_ERROR(-20902, 'Tanggal join wajib diisi untuk membuat NIK');
  END IF;

  v_period := TO_CHAR(p_join_date, 'YYYYMM');

  MERGE INTO MGTHRIS.HM_NIK_COUNTER c
  USING (SELECT p_comp_id AS comp, v_period AS p FROM DUAL) s
     ON (c.HNC_COMP_ID = s.comp AND c.HNC_PERIOD = s.p)
   WHEN NOT MATCHED THEN INSERT (HNC_COMP_ID, HNC_PERIOD, HNC_LAST_NO) VALUES (s.comp, s.p, 0);

  UPDATE MGTHRIS.HM_NIK_COUNTER
     SET HNC_LAST_NO = HNC_LAST_NO + 1,
         HNC_MODIFIED_TIMESTAMP = SYSDATE
   WHERE HNC_COMP_ID = p_comp_id
     AND HNC_PERIOD = v_period
  RETURNING HNC_LAST_NO INTO v_no;

  RETURN v_period || LPAD(v_no, 4, '0');
EXCEPTION
  WHEN OTHERS THEN
    -- ORA-02290 (CK_HNC_LAST_NO) = seri > 9999
    IF SQLCODE = -2290 THEN
      RAISE_APPLICATION_ERROR(-20901, 'Seri NIK ' || p_comp_id || ' periode ' || v_period || ' penuh (9999)');
    END IF;
    RAISE;
END FN_GEN_NIK;
/

PROMPT == 6. Trigger auto-NIK (DISABLED sampai backfill selesai) ==
CREATE OR REPLACE TRIGGER MGTHRIS.HM_EMP_DATA_TRG_NIK
BEFORE INSERT ON MGTHRIS.HM_EMP_DATA
FOR EACH ROW
FOLLOWS MGTHRIS.HM_EMP_DATA_TRG01
DISABLE
DECLARE
  v_flag VARCHAR2(1);
BEGIN
  IF :NEW.HMEMD_NIK_NEW IS NOT NULL OR NVL(:NEW.HMEMD_IS_USER_APP, 0) = 1 THEN
    RETURN;  -- NIK_NEW diisi eksplisit (migrasi) atau akun sistem
  END IF;

  BEGIN
    SELECT NVL(MAX(HNCF_VALUE), 'N') INTO v_flag
      FROM MGTHRIS.HM_NIK_CONFIG WHERE HNCF_KEY = 'AUTO_ENABLED';
  EXCEPTION WHEN OTHERS THEN v_flag := 'N';
  END;

  IF :NEW.HMEMD_JOIN_DATE IS NULL OR :NEW.HMEMD_HMCOMP_COMP_ID IS NULL THEN
    IF v_flag = 'Y' THEN
      IF :NEW.HMEMD_HMCOMP_COMP_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20904, 'Company wajib diisi untuk membuat NIK');
      END IF;
      RAISE_APPLICATION_ERROR(-20902, 'Tanggal join wajib diisi untuk membuat NIK');
    END IF;
    RETURN;  -- fase 1: dilengkapi via backfill ulang
  END IF;

  :NEW.HMEMD_NIK_NEW    := MGTHRIS.FN_GEN_NIK(:NEW.HMEMD_HMCOMP_COMP_ID, :NEW.HMEMD_JOIN_DATE);
  :NEW.HMEMD_NIK_REASON := NVL(:NEW.HMEMD_NIK_REASON, 'NEW_HIRE');  -- Duplicate Employee mengisi REHIRE/dst.

  IF :NEW.HMEMD_NIK IS NULL
     OR (v_flag = 'Y' AND NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), '-') <> 'LEGACY_NIK') THEN
    :NEW.HMEMD_NIK := :NEW.HMEMD_NIK_NEW;
  END IF;
END;
/

PROMPT == 7. Trigger immutable NIK_NEW (BR-03) ==
CREATE OR REPLACE TRIGGER MGTHRIS.HM_EMP_DATA_TRG_NIK_UPD
BEFORE UPDATE OF HMEMD_NIK_NEW ON MGTHRIS.HM_EMP_DATA
FOR EACH ROW
BEGIN
  IF :OLD.HMEMD_NIK_NEW IS NOT NULL
     AND NVL(:NEW.HMEMD_NIK_NEW, '#') <> :OLD.HMEMD_NIK_NEW
     AND NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), '-') <> 'NIK_ADMIN' THEN
    RAISE_APPLICATION_ERROR(-20903, 'NIK ' || :OLD.HMEMD_NIK_NEW || ' tidak boleh diubah');
  END IF;
END;
/

PROMPT == 8. View lookup NIK any ==
-- Bisa >1 baris per NIK_ANY (NIK lama bentrok lintas divisi / NIK baru sama di company lain):
-- aplikasi wajib filter COMP_ID/DIV_ID bila ambigu.
-- Sebelum cutover blok HRIS = NIK lama; sesudah cutover HMEMD_NIK = NIK_NEW (terfilter),
-- dan NIK lama terbaca dari map HRIS (blok ke-4).
CREATE OR REPLACE VIEW MGTHRIS.V_EMP_NIK_LOOKUP AS
SELECT e.HMEMD_NIK_NEW AS NIK_ANY, 'NIK_NEW' AS MATCH_SOURCE,
       e.HMEMD_SYS_ID, e.HMEMD_NIK_NEW AS NIK_NEW, e.HMEMD_NIK AS NIK_LEGACY,
       e.HMEMD_HMCOMP_COMP_ID AS COMP_ID, e.HMEMD_HMDIV_DIV_ID AS DIV_ID
  FROM MGTHRIS.HM_EMP_DATA e
 WHERE e.HMEMD_NIK_NEW IS NOT NULL
UNION ALL
SELECT e.HMEMD_NIK, 'HRIS',
       e.HMEMD_SYS_ID, e.HMEMD_NIK_NEW, e.HMEMD_NIK, e.HMEMD_HMCOMP_COMP_ID, e.HMEMD_HMDIV_DIV_ID
  FROM MGTHRIS.HM_EMP_DATA e
 WHERE e.HMEMD_NIK IS NOT NULL
   AND (e.HMEMD_NIK_NEW IS NULL OR e.HMEMD_NIK <> e.HMEMD_NIK_NEW)
UNION ALL
SELECT LTRIM(e.HMEMD_NIK, '0'), 'HRIS_LTRIM',
       e.HMEMD_SYS_ID, e.HMEMD_NIK_NEW, e.HMEMD_NIK, e.HMEMD_HMCOMP_COMP_ID, e.HMEMD_HMDIV_DIV_ID
  FROM MGTHRIS.HM_EMP_DATA e
 WHERE e.HMEMD_NIK LIKE '0%' AND LTRIM(e.HMEMD_NIK, '0') IS NOT NULL
UNION ALL
SELECT m.HENM_NIK_OLD, m.HENM_SOURCE,
       m.HENM_HMEMD_SYS_ID, e.HMEMD_NIK_NEW, e.HMEMD_NIK, e.HMEMD_HMCOMP_COMP_ID, m.HENM_DIV_ID
  FROM MGTHRIS.HM_EMP_NIK_MAP m
  JOIN MGTHRIS.HM_EMP_DATA e ON e.HMEMD_SYS_ID = m.HENM_HMEMD_SYS_ID
 WHERE m.HENM_SOURCE <> 'HRIS'
    OR m.HENM_NIK_OLD <> NVL(e.HMEMD_NIK, '#');   -- HRIS pra-cutover sudah tercakup blok ke-2

